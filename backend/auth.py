"""Authentication persistence and cryptographic primitives for PayPilot AI."""

import base64
import hashlib
import hmac
import re
import secrets
import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import UTC, datetime, timedelta
from pathlib import Path

from backend.database import DEFAULT_DATABASE_PATH

_USERNAME_PATTERN = re.compile(r"^[a-zA-Z0-9_.-]{3,64}$")
_PASSWORD_MIN_LENGTH = 12
_PASSWORD_MAX_LENGTH = 1024
_SCRYPT_N = 2**14
_SCRYPT_R = 8
_SCRYPT_P = 1


def _now() -> datetime:
    return datetime.now(UTC)


def _timestamp(value: datetime) -> str:
    return value.astimezone(UTC).isoformat()


def _token_hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def _hash_password(password: str) -> str:
    if not isinstance(password, str):
        raise TypeError("Password must be a string.")
    if not _PASSWORD_MIN_LENGTH <= len(password) <= _PASSWORD_MAX_LENGTH:
        raise ValueError("Password must contain between 12 and 1024 characters.")

    salt = secrets.token_bytes(16)
    derived = hashlib.scrypt(
        password.encode("utf-8"),
        salt=salt,
        n=_SCRYPT_N,
        r=_SCRYPT_R,
        p=_SCRYPT_P,
        dklen=64,
    )
    encode = lambda value: base64.urlsafe_b64encode(value).decode("ascii")
    return (
        f"scrypt${_SCRYPT_N}${_SCRYPT_R}${_SCRYPT_P}"
        f"${encode(salt)}${encode(derived)}"
    )


def _verify_password(password: str, encoded: str) -> bool:
    """Verify a password against a strictly validated scrypt representation."""
    if not isinstance(password, str) or not isinstance(encoded, str):
        return False
    if not 1 <= len(password) <= _PASSWORD_MAX_LENGTH:
        return False

    try:
        algorithm, n, r, p, salt_text, expected_text = encoded.split("$")
        if algorithm != "scrypt":
            return False

        # Accept only the parameters generated by this application.
        if (
            int(n) != _SCRYPT_N
            or int(r) != _SCRYPT_R
            or int(p) != _SCRYPT_P
        ):
            return False

        salt = base64.b64decode(
            salt_text.encode("ascii"),
            altchars=b"-_",
            validate=True,
        )
        expected = base64.b64decode(
            expected_text.encode("ascii"),
            altchars=b"-_",
            validate=True,
        )

        if len(salt) != 16 or len(expected) != 64:
            return False

        actual = hashlib.scrypt(
            password.encode("utf-8"),
            salt=salt,
            n=_SCRYPT_N,
            r=_SCRYPT_R,
            p=_SCRYPT_P,
            dklen=64,
        )
        return hmac.compare_digest(actual, expected)
    except (ValueError, TypeError, UnicodeError):
        return False


_DUMMY_HASH: str | None = None


def _dummy_password_hash() -> str:
    """Return a valid hash used to equalize timing for unknown accounts."""
    global _DUMMY_HASH
    if _DUMMY_HASH is None:
        _DUMMY_HASH = _hash_password(secrets.token_urlsafe(24))
    return _DUMMY_HASH


class AuthRepository:
    """Store user accounts, hashed sessions, and security audit events."""

    def __init__(self, database_path: str | Path = DEFAULT_DATABASE_PATH):
        self.database_path = Path(database_path)

    @contextmanager
    def _connection(self) -> Iterator[sqlite3.Connection]:
        self.database_path.parent.mkdir(parents=True, exist_ok=True)
        connection = sqlite3.connect(self.database_path, timeout=10)
        connection.execute("PRAGMA foreign_keys = ON")
        try:
            yield connection
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()

    def initialize(self) -> None:
        """Create authentication tables without altering business tables."""
        with self._connection() as connection:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS auth_users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    username TEXT NOT NULL COLLATE NOCASE UNIQUE,
                    password_hash TEXT NOT NULL,
                    role TEXT NOT NULL CHECK (role IN ('owner', 'employee')),
                    is_active INTEGER NOT NULL DEFAULT 1
                        CHECK (is_active IN (0, 1)),
                    created_at TEXT NOT NULL,
                    created_by INTEGER REFERENCES auth_users(id)
                )
            """)
            connection.execute("""
                CREATE TABLE IF NOT EXISTS auth_sessions (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id INTEGER NOT NULL
                        REFERENCES auth_users(id) ON DELETE CASCADE,
                    token_hash TEXT NOT NULL UNIQUE,
                    csrf_hash TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    expires_at TEXT NOT NULL,
                    revoked_at TEXT
                )
            """)
            connection.execute("""
                CREATE INDEX IF NOT EXISTS idx_auth_sessions_user
                ON auth_sessions(user_id)
            """)
            connection.execute("""
                CREATE TABLE IF NOT EXISTS auth_audit_events (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id INTEGER REFERENCES auth_users(id),
                    username TEXT NOT NULL,
                    event_type TEXT NOT NULL,
                    succeeded INTEGER NOT NULL CHECK (succeeded IN (0, 1)),
                    occurred_at TEXT NOT NULL
                )
            """)

    def create_user(
        self,
        username: str,
        password: str,
        role: str,
        created_by: int | None = None,
    ) -> int:
        """Create an account; caller must enforce who is authorized to do so."""
        if not isinstance(username, str):
            raise TypeError("Username must be a string.")
        normalized_username = username.strip()
        if not _USERNAME_PATTERN.fullmatch(normalized_username):
            raise ValueError(
                "Username must be 3–64 letters, digits, dots, underscores, or hyphens."
            )
        if not isinstance(role, str) or role not in {"owner", "employee"}:
            raise ValueError("Role must be owner or employee.")

        password_hash = _hash_password(password)
        created_at = _timestamp(_now())

        with self._connection() as connection:
            cursor = connection.execute(
                """
                INSERT INTO auth_users (
                    username, password_hash, role, created_at, created_by
                )
                VALUES (?, ?, ?, ?, ?)
                """,
                (normalized_username, password_hash, role, created_at, created_by),
            )
            user_id = int(cursor.lastrowid)
            connection.execute(
                """
                INSERT INTO auth_audit_events (
                    user_id, username, event_type, succeeded, occurred_at
                )
                VALUES (?, ?, 'account_created', 1, ?)
                """,
                (user_id, normalized_username, created_at),
            )
            return user_id

    def get_user_for_login(self, username: str) -> dict | None:
        """Return account data needed for login verification."""
        with self._connection() as connection:
            connection.row_factory = sqlite3.Row
            row = connection.execute(
                """
                SELECT id, username, password_hash, role, is_active
                FROM auth_users
                WHERE username = ? COLLATE NOCASE
                """,
                (username.strip(),),
            ).fetchone()
        return dict(row) if row else None

    def record_login(
        self,
        username: str,
        succeeded: bool,
        user_id: int | None = None,
    ) -> None:
        """Record a login result without storing credentials or tokens."""
        with self._connection() as connection:
            connection.execute(
                """
                INSERT INTO auth_audit_events (
                    user_id, username, event_type, succeeded, occurred_at
                )
                VALUES (?, ?, 'login', ?, ?)
                """,
                (
                    user_id,
                    username[:64],
                    int(succeeded),
                    _timestamp(_now()),
                ),
            )

    def create_session(
        self,
        user_id: int,
        ttl_hours: int = 8,
    ) -> tuple[str, str, str]:
        """Create a session and return its raw token, CSRF token, and expiry."""
        if isinstance(ttl_hours, bool) or not isinstance(ttl_hours, int):
            raise TypeError("Session lifetime must be an integer.")
        if not 1 <= ttl_hours <= 24:
            raise ValueError("Session lifetime must be between 1 and 24 hours.")

        token = secrets.token_urlsafe(32)
        csrf_token = secrets.token_urlsafe(32)
        created = _now()
        expires = created + timedelta(hours=ttl_hours)

        with self._connection() as connection:
            user = connection.execute(
                "SELECT is_active FROM auth_users WHERE id = ?",
                (user_id,),
            ).fetchone()
            if user is None or user[0] != 1:
                raise ValueError("An active account is required.")

            connection.execute(
                """
                INSERT INTO auth_sessions (
                    user_id, token_hash, csrf_hash, created_at, expires_at
                )
                VALUES (?, ?, ?, ?, ?)
                """,
                (
                    user_id,
                    _token_hash(token),
                    _token_hash(csrf_token),
                    _timestamp(created),
                    _timestamp(expires),
                ),
            )

        return token, csrf_token, _timestamp(expires)

    def get_session(self, token: str) -> dict | None:
        """Resolve a valid, unrevoked session to its active account."""
        if not isinstance(token, str) or not token or len(token) > 256:
            return None

        with self._connection() as connection:
            connection.row_factory = sqlite3.Row
            row = connection.execute(
                """
                SELECT
                    s.id AS session_id,
                    s.user_id,
                    s.csrf_hash,
                    s.expires_at,
                    u.username,
                    u.role
                FROM auth_sessions AS s
                JOIN auth_users AS u ON u.id = s.user_id
                WHERE s.token_hash = ?
                  AND s.revoked_at IS NULL
                  AND s.expires_at > ?
                  AND u.is_active = 1
                """,
                (_token_hash(token), _timestamp(_now())),
            ).fetchone()
        return dict(row) if row else None

    def validate_csrf(self, session_id: int, csrf_token: str) -> bool:
        """Compare a submitted CSRF token against the stored token hash."""
        if (
            not isinstance(csrf_token, str)
            or not csrf_token
            or len(csrf_token) > 256
        ):
            return False

        with self._connection() as connection:
            row = connection.execute(
                """
                SELECT csrf_hash
                FROM auth_sessions
                WHERE id = ? AND revoked_at IS NULL AND expires_at > ?
                """,
                (session_id, _timestamp(_now())),
            ).fetchone()

        return bool(
            row and hmac.compare_digest(row[0], _token_hash(csrf_token))
        )

    def create_initial_owner(self, username: str, password: str) -> int:
        """Atomically create the first owner account, exactly once."""
        if not isinstance(username, str):
            raise TypeError("Username must be a string.")

        normalized_username = username.strip()
        if not _USERNAME_PATTERN.fullmatch(normalized_username):
            raise ValueError(
                "Username must be 3–64 letters, digits, dots, underscores, or hyphens."
            )

        password_hash = _hash_password(password)
        created_at = _timestamp(_now())

        with self._connection() as connection:
            # Serialize competing bootstrap attempts before checking owners.
            connection.execute("BEGIN IMMEDIATE")

            existing_owner = connection.execute(
                "SELECT 1 FROM auth_users WHERE role = 'owner' LIMIT 1"
            ).fetchone()

            if existing_owner is not None:
                raise ValueError("An initial owner account already exists.")

            cursor = connection.execute(
                """
                INSERT INTO auth_users (
                    username, password_hash, role, created_at, created_by
                )
                VALUES (?, ?, 'owner', ?, NULL)
                """,
                (normalized_username, password_hash, created_at),
            )
            user_id = int(cursor.lastrowid)

            connection.execute(
                """
                INSERT INTO auth_audit_events (
                    user_id, username, event_type, succeeded, occurred_at
                )
                VALUES (?, ?, 'account_created', 1, ?)
                """,
                (user_id, normalized_username, created_at),
            )

            return user_id

    def has_owner(self) -> bool:
        """Report whether the initial owner account has been created."""
        with self._connection() as connection:
            row = connection.execute(
                "SELECT 1 FROM auth_users WHERE role = 'owner' LIMIT 1"
            ).fetchone()
        return row is not None

    def authenticate(self, username: str, password: str) -> dict | None:
        """Verify credentials, audit the attempt, and return the active user.

        Unknown, inactive, and wrong-password attempts are indistinguishable
        to the caller, and a password hash is always computed to reduce
        timing differences between them.
        """
        if (
            not isinstance(username, str)
            or not isinstance(password, str)
            or not 1 <= len(username) <= 64
        ):
            return None

        user = self.get_user_for_login(username)
        encoded = user["password_hash"] if user else _dummy_password_hash()
        password_ok = _verify_password(password, encoded)
        succeeded = bool(user and user["is_active"] == 1 and password_ok)

        self.record_login(
            username.strip(),
            succeeded,
            user["id"] if user else None,
        )
        if not succeeded or user is None:
            return None
        return {"id": user["id"], "username": user["username"], "role": user["role"]}

    def list_users(self) -> list[dict]:
        """Return all accounts without credential material."""
        with self._connection() as connection:
            connection.row_factory = sqlite3.Row
            rows = connection.execute(
                """
                SELECT id, username, role, is_active, created_at
                FROM auth_users
                ORDER BY id
                """
            ).fetchall()
        return [dict(row) for row in rows]

    def set_user_active(self, user_id: int, active: bool, actor_id: int) -> bool:
        """Activate or deactivate an employee account.

        Owners cannot be changed here and nobody can change their own
        account. Deactivation also revokes the account's live sessions.
        Returns False when the account does not exist.
        """
        if isinstance(user_id, bool) or not isinstance(user_id, int):
            return False
        if user_id == actor_id:
            raise ValueError("You cannot change your own account.")

        now = _timestamp(_now())
        with self._connection() as connection:
            row = connection.execute(
                "SELECT username, role FROM auth_users WHERE id = ?",
                (user_id,),
            ).fetchone()
            if row is None:
                return False
            username, role = row
            if role != "employee":
                raise ValueError("Only employee accounts can be changed.")

            connection.execute(
                "UPDATE auth_users SET is_active = ? WHERE id = ?",
                (1 if active else 0, user_id),
            )
            if not active:
                connection.execute(
                    """
                    UPDATE auth_sessions SET revoked_at = ?
                    WHERE user_id = ? AND revoked_at IS NULL
                    """,
                    (now, user_id),
                )
            connection.execute(
                """
                INSERT INTO auth_audit_events (
                    user_id, username, event_type, succeeded, occurred_at
                )
                VALUES (?, ?, ?, 1, ?)
                """,
                (
                    user_id,
                    username,
                    "account_reactivated" if active else "account_deactivated",
                    now,
                ),
            )
        return True

    def rotate_csrf_token(self, session_id: int) -> str | None:
        """Replace a valid session's CSRF secret and return it once."""
        if isinstance(session_id, bool) or not isinstance(session_id, int):
            return None

        csrf_token = secrets.token_urlsafe(32)

        with self._connection() as connection:
            cursor = connection.execute(
                """
                UPDATE auth_sessions
                SET csrf_hash = ?
                WHERE id = ?
                  AND revoked_at IS NULL
                  AND expires_at > ?
                  AND EXISTS (
                      SELECT 1
                      FROM auth_users
                      WHERE auth_users.id = auth_sessions.user_id
                        AND auth_users.is_active = 1
                  )
                """,
                (
                    _token_hash(csrf_token),
                    session_id,
                    _timestamp(_now()),
                ),
            )

            if cursor.rowcount != 1:
                return None

        return csrf_token

    def revoke_session(self, token: str) -> bool:
        """Revoke a session by its raw cookie token."""
        if not isinstance(token, str) or not token or len(token) > 256:
            return False

        with self._connection() as connection:
            cursor = connection.execute(
                """
                UPDATE auth_sessions
                SET revoked_at = ?
                WHERE token_hash = ? AND revoked_at IS NULL
                """,
                (_timestamp(_now()), _token_hash(token)),
            )
            return cursor.rowcount == 1
